def table(headers,rows,widths=None,y=538,size=23):
    widths=widths or [1160/len(headers)]*len(headers)
    sty=ParagraphStyle('cell',fontName='JP',fontSize=size,leading=size*1.42,wordWrap='CJK',textColor=INK)
    hs=ParagraphStyle('head',parent=sty,textColor=white,fontSize=size-1)
    data=[[Paragraph(escape(str(v)).replace('\n','<br/>'),hs) for v in headers]]
    data += [[Paragraph(escape(str(v)).replace('\n','<br/>'),sty) for v in row] for row in rows]
    t=Table(data,colWidths=widths,hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),NAVY),('VALIGN',(0,0),(-1,-1),'TOP'),
        ('LEFTPADDING',(0,0),(-1,-1),13),('RIGHTPADDING',(0,0),(-1,-1),13),
        ('TOPPADDING',(0,0),(-1,-1),12),('BOTTOMPADDING',(0,0),(-1,-1),12),
        ('LINEBELOW',(0,1),(-1,-1),.6,RULE),('ROWBACKGROUNDS',(0,1),(-1,-1),[white,PAPER])]))
    _,h=t.wrap(1160,10000)
