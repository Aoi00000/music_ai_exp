def box(x,y,w,h,label):
    if current is None:return
    for old in current['boxes']:
        ox,oy,ow,oh,other=old
        if min(x+w,ox+ow)-max(x,ox)>1 and min(y+h,oy+oh)-max(y,oy)>1:
            raise ValueError(f'Overlap page {len(pages)}: {label[:35]} / {other[:35]}')
    current['boxes'].append((x,y,w,h,label))

def para(text,x,y,w,size=25,color=INK,leading=None):
    style=ParagraphStyle('p',fontName='JP',fontSize=size,leading=leading or size*1.48,textColor=color,wordWrap='CJK',splitLongWords=True)
    p=Paragraph(escape(str(text)).replace('\n','<br/>'),style)
    _,h=p.wrap(w,10000)
    if y-h<82:raise ValueError(f'Overflow page {len(pages)}: {str(text)[:70]} at {y-h}')
    box(x,y-h,w,h,str(text))
    p.drawOn(c,x,y-h)
    if current is not None:current['text'].append(str(text))
    return y-h

